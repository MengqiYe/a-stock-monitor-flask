    """合并股票列表并去重"""
    seen = set()
    result = []
    # 优先添加上证50
    for stock in SZ50_STOCKS:
        if stock['code'] not in seen:
            seen.add(stock['code'])
            result.append(stock)
    # 再添加中证500中不重复的
    for stock in ZZ500_STOCKS:
        if stock['code'] not in seen:
            seen.add(stock['code'])
            result.append(stock)
    return result

